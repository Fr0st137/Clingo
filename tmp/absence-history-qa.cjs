const assert = require('node:assert/strict');
const { chromium } = require('C:/Users/pc/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1920, height: 915 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/provider/**', route => route.fulfill({ json: new URL(route.request().url()).pathname.endsWith('/me') ? { user: { name: 'Test', email: 'test@example.test' }, account: { id: 'qa', name: 'Firma testowa', role: 'owner' } } : [] }));
  async function open() {
    await page.getByRole('button', { name: 'Dodaj zdarzenie', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Nieobecność (urlop, choroba)', exact: true }).click();
    await page.getByRole('button', { name: 'Historia nieobecności', exact: true }).click();
    await page.getByRole('heading', { name: 'Historia nieobecnościami', exact: true }).waitFor();
  }
  await page.goto('http://127.0.0.1:3108/');
  await open();
  const dialog = page.getByRole('dialog');
  const rows = dialog.locator('tbody tr');
  assert.equal(await rows.count(), 4);
  assert.equal(await dialog.locator('th').count(), 5);
  assert.equal(await dialog.locator('.absence-delete').count(), 0);
  assert.deepEqual(await dialog.locator('.absence-status').allTextContents(), Array(4).fill('Zakończona'));
  assert.equal((await dialog.boundingBox()).width, 1000);
  const assets = await dialog.locator('img').evaluateAll(images => images.filter(img => img.getBoundingClientRect().width).map(img => ({ src: img.getAttribute('src'), ok: img.complete && img.naturalWidth > 0, w: img.getBoundingClientRect().width, h: img.getBoundingClientRect().height })));
  assert(assets.every(img => img.ok));
  console.log('assets', JSON.stringify(assets));
  await page.screenshot({ path: 'tmp/absence-history-figma-after.png' });
  await page.getByLabel('Numer nieobecności', { exact: true }).fill('15');
  assert.equal(await rows.count(), 1);
  await page.getByLabel('Numer nieobecności', { exact: true }).fill('999');
  assert.equal(await rows.count(), 0);
  await dialog.getByRole('status').waitFor();
  await page.getByLabel('Numer nieobecności', { exact: true }).fill('');
  await page.getByLabel('Rok', { exact: true }).selectOption('2026');
  await page.getByLabel('Miesiąc', { exact: true }).selectOption('01');
  assert.equal(await rows.count(), 1);
  await page.getByLabel('Miesiąc', { exact: true }).selectOption('');
  await page.getByLabel('Rok', { exact: true }).selectOption('');
  await page.getByLabel('Pracownik', { exact: true }).selectOption('Paulina Jagielska');
  assert.equal(await rows.count(), 3);
  await page.getByLabel('Pracownik', { exact: true }).selectOption('');
  await page.getByLabel('Sortowanie', { exact: true }).selectOption('start-asc');
  assert.match(await rows.first().innerText(), /^14/);
  await page.getByRole('button', { name: /Pracownicy nieobecności 15:/ }).click();
  assert.equal(await dialog.locator('.absence-names-detail').count(), 1);
  await page.keyboard.press('Escape');
  assert(await page.getByRole('button', { name: 'Dodaj zdarzenie', exact: true }).evaluate(el => el === document.activeElement));
  await page.setViewportSize({ width: 390, height: 844 });
  await open();
  assert(await dialog.locator('.provider-modal-body').evaluate(el => el.scrollWidth <= el.clientWidth));
  const closeBox = await page.getByRole('button', { name: 'Zamknij', exact: true }).boundingBox();
  assert(closeBox.y >= 0);
  await dialog.locator('.absence-table-scroll').evaluate(el => el.scrollLeft = el.scrollWidth);
  await page.screenshot({ path: 'tmp/absence-history-mobile.png' });
  await page.getByRole('button', { name: 'Zamknij', exact: true }).click();
  assert.deepEqual(errors, []);
  console.log('OK: history opens, 1000px width, completed rows, no delete action, filters, sorting, employee details, empty state, focus, mobile scrolling, close.');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
